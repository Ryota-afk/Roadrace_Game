//
// 【解像度を揃えた経緯・重要】
// 最初に受け取った自転車の参考画像は58×80マス相当で描かれており、人物(16×36)と並べると
// 1マスの実寸が2.2倍違って「人物はカクカク、自転車は滑らか」というチグハグな絵になった
// （粒度差はまさに"安っぽさ"の原因になるため看過できない）。低解像度へ落として揃えようと
// したが、22×30/29×40では自転車の形が判別不能まで潰れた。そこでユーザーに粗い粒度で
// 参考画像を描き直してもらい、人物と同じ「1マス≒6px」の絵として取り直したのが本データ。
// 人物側(pixelPerson.jsx)は16×36のまま変更していない。
//
// 抽出は scratchpad のPillowスクリプトで実施：背景を透明化 → 面積平均(BOX)で縮小 →
// アルファを閾値30で二値化（車輪のスポークが細く、閾値が高いと車輪が輪だけになって
// 穴が空く）→ 連結成分の最大だけ残す（ラベル等の混入を落とす）→ パレットへ最近傍写像。
//
// 参考画像は輪郭ドットを含むため、`pixelSprite`の自動縁取りは false で呼ぶこと。
